package com.mealManage.domain;

public class AccBalanceSummary {
	
	private String schoolName;
	private Double stdAccBalance;
	private Double stdNegativeBalance;
	private Double staffAccBalance;
	private Double staffNegativeBalance;
	/**
	 * @return the schoolName
	 */
	public String getSchoolName() {
		return schoolName;
	}
	/**
	 * @param schoolName the schoolName to set
	 */
	public void setSchoolName(String schoolName) {
		this.schoolName = schoolName;
	}
	/**
	 * @return the stdAccBalance
	 */
	public Double getStdAccBalance() {
		return stdAccBalance;
	}
	/**
	 * @param stdAccBalance the stdAccBalance to set
	 */
	public void setStdAccBalance(Double stdAccBalance) {
		this.stdAccBalance = stdAccBalance;
	}
	/**
	 * @return the stdNegativeBalance
	 */
	public Double getStdNegativeBalance() {
		return stdNegativeBalance;
	}
	/**
	 * @param stdNegativeBalance the stdNegativeBalance to set
	 */
	public void setStdNegativeBalance(Double stdNegativeBalance) {
		this.stdNegativeBalance = stdNegativeBalance;
	}
	/**
	 * @return the staffAccBalance
	 */
	public Double getStaffAccBalance() {
		return staffAccBalance;
	}
	/**
	 * @param staffAccBalance the staffAccBalance to set
	 */
	public void setStaffAccBalance(Double staffAccBalance) {
		this.staffAccBalance = staffAccBalance;
	}
	/**
	 * @return the staffNegativeBalance
	 */
	public Double getStaffNegativeBalance() {
		return staffNegativeBalance;
	}
	/**
	 * @param staffNegativeBalance the staffNegativeBalance to set
	 */
	public void setStaffNegativeBalance(Double staffNegativeBalance) {
		this.staffNegativeBalance = staffNegativeBalance;
	}
	
}
