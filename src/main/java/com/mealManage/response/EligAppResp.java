package com.mealManage.response;

public class EligAppResp {
	
	private String stdFirstName;
	private String stdLastName;
	private Long stdRecId;
	private String appStatus;
	private String grade;
	private String eligibility;
	private Long appId;
	/**
	 * @return the stdFirstName
	 */
	public String getStdFirstName() {
		return stdFirstName;
	}
	/**
	 * @param stdFirstName the stdFirstName to set
	 */
	public void setStdFirstName(String stdFirstName) {
		this.stdFirstName = stdFirstName;
	}
	/**
	 * @return the stdLastName
	 */
	public String getStdLastName() {
		return stdLastName;
	}
	/**
	 * @param stdLastName the stdLastName to set
	 */
	public void setStdLastName(String stdLastName) {
		this.stdLastName = stdLastName;
	}
	/**
	 * @return the stdRecId
	 */
	public Long getStdRecId() {
		return stdRecId;
	}
	/**
	 * @param stdRecId the stdRecId to set
	 */
	public void setStdRecId(Long stdRecId) {
		this.stdRecId = stdRecId;
	}
	/**
	 * @return the appStatus
	 */
	public String getAppStatus() {
		return appStatus;
	}
	/**
	 * @param appStatus the appStatus to set
	 */
	public void setAppStatus(String appStatus) {
		this.appStatus = appStatus;
	}
	/**
	 * @return the grade
	 */
	public String getGrade() {
		return grade;
	}
	/**
	 * @param grade the grade to set
	 */
	public void setGrade(String grade) {
		this.grade = grade;
	}
	/**
	 * @return the eligibility
	 */
	public String getEligibility() {
		return eligibility;
	}
	/**
	 * @param eligibility the eligibility to set
	 */
	public void setEligibility(String eligibility) {
		this.eligibility = eligibility;
	}
	/**
	 * @return the appId
	 */
	public Long getAppId() {
		return appId;
	}
	/**
	 * @param appId the appId to set
	 */
	public void setAppId(Long appId) {
		this.appId = appId;
	}
}
